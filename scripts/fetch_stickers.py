#!/usr/bin/env python3
"""Fetch the bird-card stickers and facts for every species in _data/species.yml.

The Avians cards show each species as an illustrated sticker (user, 2026-10-31) from Huashu's
bird-sticker library (the user's fork: ronghao-zhang-gallery/huashu-bird-sticker). The library is
1.4 GB, more than GitHub Pages serves, so only the stickers the site needs are copied here, made
small for the card: assets/images/stickers/<species id>.webp.

Species are matched by scientific name first (`scientific:` in species.yml, genus and species
only; both use IOC names), then by eBird code (`ebird:`, `ids.ebird` in the library's
data/species.json). The name comes first because codes can disagree after a split: the
library files Hudsonian Whimbrel under whimbr3 and has no code for Western Cattle Egret, while
eBird Status & Trends uses whimbr and categr1. A species already fetched is skipped; pass
--force to fetch it again.

It also writes _data/bird_facts.yml (rewritten on every run, for every species) with what the
cards show under the sighting (user, 2026-10-31):
  morphology  mean weight (g), wing and tail length (mm), from AVONET (Tobias et al. 2022,
              CC BY 4.0: the Avians page credits it). Body length is in the library for only a
              third of the birds, so it is left out to keep every card alike.
  iucn        IUCN Red List category (LC, NT, VU, EN, CR, EW, EX or DD), via Wikidata (CC0).

Licence: the stickers are PolyForm Shield 1.0.0 (free for a personal site; not for a competing
bird-watching app or service). The licence text and Required Notice sit beside them in
assets/images/stickers/LICENSE.md, and the Avians page credits them. Keep both.

  python scripts/fetch_stickers.py                     # download from GitHub
  python scripts/fetch_stickers.py --repo ../huashu-bird-sticker   # or read a local clone

Needs Pillow (the gallery conda env has it).
"""

# ---- Imports and settings ----
import argparse
import io
import json
import sys
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SPECIES_YML = ROOT / "_data" / "species.yml"
FACTS_YML = ROOT / "_data" / "bird_facts.yml"
OUT_DIR = ROOT / "assets" / "images" / "stickers"
RAW = "https://raw.githubusercontent.com/ronghao-zhang-gallery/huashu-bird-sticker/main/"

# The card's sticker slot is about 100 × 75 CSS px; 360 px on the long edge stays sharp on
# 3× screens and keeps each file around 15–25 KB.
LONG_EDGE = 360
QUALITY = 86


# ---- Reading the library (GitHub or a local clone) ----
def reader(repo):
    """Return a function that reads one file of the library as bytes."""
    if repo:
        base = Path(repo)
        return lambda rel: (base / rel).read_bytes()

    def fetch(rel):
        with urllib.request.urlopen(RAW + rel, timeout=60) as r:
            return r.read()
    return fetch


def site_species():
    """{species id: {"ebird", "iucn", "scientific"}} from species.yml (read as plain text, so
    no YAML library is needed). `iucn:` there is a hand-set category for a species the library
    has none for; `scientific` is cut to genus and species (Osprey carries a subspecies)."""
    out, current = {}, None
    for line in SPECIES_YML.read_text().splitlines():
        if line and not line[0].isspace() and line.rstrip().endswith(":") and not line.startswith("#"):
            current = line.rstrip()[:-1]
            out[current] = {"ebird": None, "iucn": None, "scientific": None}
        elif current:
            key = line.strip().split(":", 1)[0]
            if key in ("ebird", "iucn", "scientific"):
                out[current][key] = line.split(":", 1)[1].split("#")[0].strip()
    for v in out.values():
        if v["scientific"]:
            v["scientific"] = " ".join(v["scientific"].split()[:2])
    return {sid: v for sid, v in out.items() if v["ebird"]}


# ---- Facts for the cards ----
def facts_of(entry):
    """The card's facts for one library entry: rounded measurements and the IUCN category."""
    traits = entry.get("traits") or {}
    out = {}
    if traits.get("massG"):
        m = traits["massG"]
        out["weight_g"] = round(m) if m >= 10 else round(m, 1)   # 26 g, but 8.5 g
    for key, name in (("wingMm", "wing_mm"), ("tailMm", "tail_mm")):
        if traits.get(key):
            out[name] = round(traits[key])
    iucn = (entry.get("conservation") or {}).get("iucn")
    if iucn:
        out["iucn"] = iucn
    return out


def write_facts(facts):
    """Write _data/bird_facts.yml: one short block per species, in species.yml's order."""
    lines = [
        "# Facts for the Avians bird cards. GENERATED by scripts/fetch_stickers.py; do not edit,",
        "# rerun the script. Measurements: AVONET (Tobias et al. 2022, CC BY 4.0), species means;",
        "# IUCN Red List category via Wikidata (CC0). Both from the huashu-bird-sticker library.",
        "",
    ]
    for sid, f in facts.items():
        lines.append(f"{sid}:")
        # Credits are quoted (URLs hold colons); numbers and IUCN codes are written bare.
        lines += [f"  {k}: {json.dumps(v, ensure_ascii=False) if k.startswith('sticker_') else v}" for k, v in f.items()]
    FACTS_YML.write_text("\n".join(lines) + "\n")


# ---- Main ----
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", help="path to a local clone of huashu-bird-sticker (default: GitHub)")
    ap.add_argument("--force", action="store_true", help="fetch stickers that already exist again")
    args = ap.parse_args()

    read = reader(args.repo)
    library = json.loads(read("data/species.json"))["species"]
    # A few entries carry a list of eBird codes (e.g. after a split), most a single one.
    by_ebird, by_name = {}, {s["scientificName"]: s for s in library}
    for s in library:
        codes = (s.get("ids") or {}).get("ebird") or []
        for code in [codes] if isinstance(codes, str) else codes:
            by_ebird.setdefault(code, s)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    missing, facts = [], {}
    for sid, info in site_species().items():
        code = info["ebird"]
        entry = by_name.get(info["scientific"]) or by_ebird.get(code)
        if not entry:
            missing.append(f"{sid} ({code})")
            continue
        facts[sid] = facts_of(entry)
        # A photo-cutout sticker keeps its photo's licence (e.g. CC BY), which asks for the
        # photographer's name: kept here, and the Avians credit line names them (2026-11-04).
        sticker = entry["sticker"]
        if sticker["kind"] != "ai-illustration":
            src = sticker.get("source") or {}
            facts[sid]["sticker_by"] = src.get("author") or "unknown"
            facts[sid]["sticker_license"] = sticker.get("license") or ""
            facts[sid]["sticker_url"] = src.get("page") or sticker.get("licenseURL") or ""
        if info["iucn"]:
            facts[sid]["iucn"] = info["iucn"]          # set by hand in species.yml
        elif "iucn" not in facts[sid]:
            print(f"    note: {sid} has no IUCN category in the library; set `iucn:` in species.yml")
        out = OUT_DIR / f"{sid}.webp"
        if out.exists() and not args.force:
            print(f"  {sid}: sticker already there")
            continue
        im = Image.open(io.BytesIO(read(sticker["file"]))).convert("RGBA")
        im.thumbnail((LONG_EDGE, LONG_EDGE), Image.LANCZOS)
        # Written under a hidden name (Jekyll skips dotfiles), then renamed: a running
        # `jekyll serve` once copied laughing-gull.webp half-written, as an empty file
        # (2026-10-31), and kept it.
        part = out.with_name("." + out.name + ".part")
        im.save(part, "WEBP", quality=QUALITY, method=6)
        part.replace(out)
        print(f"  {sid}: {entry['id']} ({sticker['kind']}, {sticker['license']}) -> {out.relative_to(ROOT)}, "
              f"{out.stat().st_size // 1024} KB")
        # The 34 photo-cutout stickers keep their photo's own licence, not PolyForm Shield;
        # their credit goes into bird_facts.yml (above) and onto the page.
        if sticker["kind"] != "ai-illustration":
            print(f"    note: {sticker['kind']}, licence {sticker['license']}; credited on the page")

    write_facts(facts)
    print(f"wrote {FACTS_YML.relative_to(ROOT)} ({len(facts)} species)")
    if missing:
        print("Not in the sticker library: " + ", ".join(missing), file=sys.stderr)


if __name__ == "__main__":
    main()
