"""Make local copies of the Chinese web-font lists (CSS) with font-display: block.

The Chinese fonts (霞鹜文楷 for Simplified, 汇文明朝体 for Traditional) come in hundreds of small
pieces from jsDelivr; their CSS lists every piece with font-display: swap, so a new page first
drew its Chinese in a stand-in font and then switched (user, 2026-10-25). This script copies each
list into assets/fonts/, with
  - font-display: block (text waits briefly for its font instead of showing a stand-in), and
  - every piece's address made absolute, so the files still come from jsDelivr.
lang-init.html loads the copy for the page's language, render-blocking, so it is known by the
first paint. Rerun after changing a font version below.

Run (any Python 3):  python scripts/make_cjk_font_css.py
"""

import re
import urllib.parse
import urllib.request
from pathlib import Path

FONTS = {
    # local file: package CSS on jsDelivr
    'lxgw-wenkai.css': 'https://cdn.jsdelivr.net/npm/lxgw-wenkai-webfont@1.7.0/lxgwwenkai-regular.css',
    'huiwen-mincho.css': 'https://cdn.jsdelivr.net/npm/@chinese-fonts/hwmct@3.0.0/dist/'
                         + urllib.parse.quote('汇文明朝体') + '/result.css',
}

OUT = Path(__file__).resolve().parent.parent / 'assets' / 'fonts'


def main():
    for name, url in FONTS.items():
        css = urllib.request.urlopen(url).read().decode()
        base = url.rsplit('/', 1)[0] + '/'
        # Relative piece addresses → absolute (the pieces stay on jsDelivr).
        css = re.sub(r"url\((['\"]?)\.?/?([^)'\"]+)\1\)",
                     lambda m: f'url("{urllib.parse.urljoin(base, m.group(2))}")', css)
        swaps = len(re.findall(r'font-display:\s*swap', css))
        css = re.sub(r'font-display:\s*swap', 'font-display:block', css)
        header = (f'/* GENERATED by scripts/make_cjk_font_css.py from {url}\n'
                  f'   font-display swap → block; piece addresses made absolute. Do not edit. */\n')
        (OUT / name).write_text(header + css)
        print(f'{name}: {swaps} faces, {len(css) // 1024} KB')


if __name__ == '__main__':
    main()
