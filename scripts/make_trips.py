#!/usr/bin/env python3
"""Write the birding trip log, _data/trips.yml, from the sightings in _data/avians.yml.

The user wants a record of every birding trip and the birds seen on it (user, 2026-11-03:
"a document on the backend stating each birding trip details, what birds do I see each
time"). avians.yml stays the one place sightings are entered (by hand or add_sighting.py);
this log is made from it, so the two can never disagree. The Avians page shows it as its
Checklist table under the gallery (user, 2026-11-03; _includes/avians/checklist.html), taking
names in all three languages from the ids (`place_id`, each bird's `id`).

A trip is one day at one place (Savannah NWR on 2026-04-18 and Fort Pulaski the next day are
two trips). Trips run newest first; within a trip the birds are in the order they were seen
(`taken`), birds without a time keeping their order in avians.yml, like the Avians cards.

  python scripts/make_trips.py        # after any change to avians.yml (add_sighting.py runs it)

Needs PyYAML (the gallery env has it).
"""

# ---- Imports and paths ----
from collections import OrderedDict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
AVIANS = ROOT / '_data' / 'avians.yml'
SPECIES = ROOT / '_data' / 'species.yml'
OUT = ROOT / '_data' / 'trips.yml'


def q(s):
    """A YAML string in double quotes (names hold commas, colons and apostrophes)."""
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


# ---- Grouping: one trip per date and place ----
def trips(data, species):
    places = {p['id']: p for p in data['places']}
    by_trip = OrderedDict()
    for v in data['visits']:
        by_trip.setdefault((v['date'], v['place']), []).append(v)

    out = []
    for (date, place), rows in by_trip.items():
        # Order seen: by `taken`, birds with no time of day after the timed ones (when they were
        # seen that day isn't known). Python's sort is stable, so ties keep avians.yml's order.
        def seen(v):
            taken = str(v.get('taken') or v['date'])
            return ('T' not in taken, taken)
        rows = sorted(rows, key=seen)
        birds = OrderedDict()
        for v in rows:
            b = birds.setdefault(v['species'], {'photos': 0, 'count': None})
            if v.get('photo'):
                b['photos'] += 1
            if v.get('count'):                     # how many were counted (eBird checklists)
                b['count'] = (b['count'] or 0) + v['count']
        out.append({'date': date, 'place': places[place], 'birds': birds})
    out.sort(key=lambda t: t['date'], reverse=True)
    return out


# ---- Writing (by hand, so the file reads like a log) ----
def write(all_trips, species):
    n_birds = len({sid for t in all_trips for sid in t['birds']})
    lines = [
        '# Birding trips: every outing and the birds seen on it (user, 2026-11-03).',
        '# GENERATED by scripts/make_trips.py from _data/avians.yml. Do not edit; change',
        '# avians.yml and rerun the script. Shown on Avians as the Checklist table.',
        '# A trip is one day at one place, newest first; birds in the order they were seen.',
        '# photos: how many of that bird\'s photos from the trip are on the site (0 = seen only).',
        '# count: how many were counted, when the checklist gave it.',
        f'# {len(all_trips)} trips, {n_birds} species.',
        '',
    ]
    for t in all_trips:
        p, birds = t['place'], t['birds']
        shot = sum(b['photos'] for b in birds.values())
        lines += [
            f'- date: {q(t["date"])}',
            f'  place: {q(p["name"]["en"])}   # {p["name"]["zh"]}',
            f'  place_id: {p["id"]}',
            f'  species: {len(birds)}',
            f'  photos: {shot}',
            '  birds:',
        ]
        for sid, b in birds.items():
            sp = species[sid]
            lines.append(f'    - {{ id: {sid}, bird: {q(sp["name"]["en"])}, zh: {sp["name"]["zh"]}, '
                         f'scientific: {q(sp.get("scientific", ""))}, photos: {b["photos"]}'
                         + (f', count: {b["count"]}' if b['count'] else '') + ' }')
        lines.append('')
    OUT.write_text('\n'.join(lines), encoding='utf-8')


# ---- Main ----
def main():
    data = yaml.safe_load(AVIANS.read_text(encoding='utf-8'))
    species = yaml.safe_load(SPECIES.read_text(encoding='utf-8'))
    all_trips = trips(data, species)
    write(all_trips, species)
    print(f'wrote {OUT.relative_to(ROOT)}: {len(all_trips)} trips')
    for t in all_trips:
        print(f'  {t["date"]}  {t["place"]["name"]["en"]}: {len(t["birds"])} species')


if __name__ == '__main__':
    main()
