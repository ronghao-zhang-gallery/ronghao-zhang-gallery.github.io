#!/usr/bin/env python3
"""Which continents each bird's range reaches, for the Avians continent view.

Zoomed into one continent, the Avians map shows only that continent, so a bird whose range runs
on into others (Osprey, Great Egret, Ruddy Turnstone…) looks like a bird of that continent only.
The page marks the other continents its range reaches (user, 2026-10-31: "some birds are
distributed not only in one continent; in the continent view, indicate that").

Reads the ranges (_data/ranges.yml, from make_ranges.py) and the continents' shapes (the mask
in _includes/places/world-map-plain.svg, the same shapes the page fades the other continents
with), lays both on one grid with the map's land, and writes _data/range_continents.yml (GENERATED): per eBird code,
the continents holding at least MIN_AREA of its range, in the continent bar's order.
Only land counts, as on the page (ranges are drawn clipped to the land): the continents' shapes
also take in the sea nearest them, and range outlines spill a little past the coast, which put
two American shorebirds in "Europe" over the Arctic Ocean. Antarctica has no shape there (it has
its own map), so it is never listed.

make_ranges.py runs this at the end; run it by hand after changing either input:
  python scripts/range_continents.py
Needs Pillow, NumPy and PyYAML (the gallery env).
"""

# ---- Imports and settings ----
import re
from pathlib import Path

import numpy as np
import yaml
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RANGES = ROOT / '_data' / 'ranges.yml'
CONTINENTS = ROOT / '_data' / 'continents.yml'
WORLD = ROOT / '_includes' / 'places' / 'world-map-plain.svg'
OUT = ROOT / '_data' / 'range_continents.yml'

PX = 4          # grid cells per map unit (one unit is about 0.6° of longitude)
# Least share of a range, in map units² (~ 4,500 km² at the equator), for a continent to count:
# keeps out slivers where a range only brushes a continent's edge, but keeps thin coastal ranges.
MIN_AREA = 1.0


# ---- Path data (only M, l and z: what make_world_map.py and make_ranges.py write) ----
def polygons(d):
    """Split path data into lists of absolute (x, y) points, one per subpath."""
    out, pts, x, y = [], [], 0.0, 0.0
    for cmd, args in re.findall(r'([MLlz])([^MLlz]*)', d):
        nums = [float(n) for n in re.findall(r'-?(?:\d+\.?\d*|\.\d+)', args)]
        if cmd == 'M':
            if len(pts) > 2:
                out.append(pts)
            x, y = nums[0], nums[1]
            pts = [(x, y)]
            nums = nums[2:]
            cmd = 'l'                        # extra pairs after M are lines, relative here
        if cmd in 'lL':
            for i in range(0, len(nums) - 1, 2):
                if cmd == 'l':
                    x, y = x + nums[i], y + nums[i + 1]
                else:
                    x, y = nums[i], nums[i + 1]
                pts.append((x, y))
        if cmd == 'z' and len(pts) > 2:
            out.append(pts)
            pts = []
    if len(pts) > 2:
        out.append(pts)
    return out


def raster(d, box):
    """The area a path covers, as a boolean grid over box (x0, y0, width, height)."""
    x0, y0, w, h = box
    im = Image.new('1', (int(w * PX), int(h * PX)), 0)
    draw = ImageDraw.Draw(im)
    for poly in polygons(d):
        draw.polygon([((px - x0) * PX, (py - y0) * PX) for px, py in poly], fill=1)
    return np.array(im, dtype=bool)


# ---- Main ----
def main():
    svg = WORLD.read_text(encoding='utf-8')
    mask = svg[svg.index('<mask id="world-map-focus"'):]
    mask = mask[:mask.index('</mask>')]
    m = re.search(r'x="([-\d.]+)" y="([-\d.]+)" width="([\d.]+)" height="([\d.]+)"', mask)
    box = tuple(float(v) for v in m.groups())
    shapes = dict(re.findall(r'<path[^>]*data-continent="([a-z-]+)"[^>]*\sd="([^"]+)"', mask))
    land = raster(re.search(r'<path[^>]*id="world-map-land-shape"[^>]*\sd="([^"]+)"', svg).group(1), box)

    order = [c['id'] for c in yaml.safe_load(CONTINENTS.read_text(encoding='utf-8'))]
    areas = {c: raster(shapes[c], box) & land for c in order if c in shapes}
    ranges = yaml.safe_load(RANGES.read_text(encoding='utf-8')) or {}

    result = {}
    for code, seasons in sorted(ranges.items()):
        cover = np.zeros_like(next(iter(areas.values())))
        for key, d in seasons.items():
            if key != 'source':
                cover |= raster(d, box)
        found = []
        for c in order:
            if c in areas:
                share = (cover & areas[c]).sum() / PX ** 2
                if share >= MIN_AREA:
                    found.append(c)
        result[code] = found
        print(f'  {code}: {", ".join(found) or "-"}')

    header = ('# GENERATED by scripts/range_continents.py from _data/ranges.yml and the continent\n'
              '# shapes in world-map-plain.svg. Do not edit; rerun the script. Per eBird code: the\n'
              '# continents its range reaches, for the Avians continent view.\n')
    OUT.write_text(header + yaml.safe_dump(result, sort_keys=True, default_flow_style=None),
                   encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
