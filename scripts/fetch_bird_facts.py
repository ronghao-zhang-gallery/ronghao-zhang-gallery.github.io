#!/usr/bin/env python3
"""Write the Avians bird cards' facts for every species in _data/species.yml.

The facts come from the data of Huashu's bird-sticker library (the user's fork:
ronghao-zhang-gallery/huashu-bird-sticker; its compiled data is MIT). Only the data is used:
the site's stickers were removed (user, 2026-11-04), because they are AI drawings made from
other people's photos, most of them under non-commercial or all-rights-reserved terms. Don't
bring stickers back without asking. This script replaced fetch_stickers.py.

Species are matched by scientific name first (`scientific:` in species.yml, genus and species
only), then by eBird code (`ebird:`, `ids.ebird` in the library's data/species.json). The name
comes first because codes can disagree after a split: the library files Hudsonian Whimbrel
under whimbr3 and has no code for Western Cattle Egret, while eBird Status & Trends uses
whimbr and categr1.

It writes _data/bird_facts.yml (rewritten on every run, for every species) with what the
cards show under the sighting (user, 2026-10-31):
  morphology  mean weight (g), wing and tail length (mm), from AVONET (Tobias et al. 2022,
              CC BY 4.0: the Avians page credits it). Body length is in the library for only
              a third of the birds, so it is left out to keep every card alike.
  iucn        IUCN Red List category (LC, NT, VU, EN, CR, EW, EX or DD) from the library, or
              `iucn:` set by hand in species.yml, which wins.

  python scripts/fetch_bird_facts.py                                 # read from GitHub
  python scripts/fetch_bird_facts.py --repo ../huashu-bird-sticker   # or a local clone

Run it after adding a species. Standard library only.
"""

# ---- Imports and settings ----
import argparse
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECIES_YML = ROOT / "_data" / "species.yml"
FACTS_YML = ROOT / "_data" / "bird_facts.yml"
RAW = "https://raw.githubusercontent.com/ronghao-zhang-gallery/huashu-bird-sticker/main/"


# ---- Reading the library's data (GitHub or a local clone) ----
def read_library(repo):
    """The library's species records (data/species.json)."""
    if repo:
        raw = (Path(repo) / "data" / "species.json").read_bytes()
    else:
        with urllib.request.urlopen(RAW + "data/species.json", timeout=120) as r:
            raw = r.read()
    return json.loads(raw)["species"]


def site_species():
    """{species id: {"ebird", "iucn", "scientific"}} from species.yml (read as plain text, so
    no YAML library is needed: a species' key line must end in ":" with no comment after it).
    `iucn:` there is a hand-set category for a species the library has none for; `scientific`
    is cut to genus and species (Osprey carries a subspecies)."""
    out, current = {}, None
    for line in SPECIES_YML.read_text().splitlines():
        if line and not line[0].isspace() and line.rstrip().endswith(":") and not line.startswith("#"):
            current = line.rstrip()[:-1]
            out[current] = {"ebird": None, "iucn": None, "scientific": None}
        elif current:
            key = line.strip().split(":", 1)[0]
            if key in ("ebird", "iucn", "scientific"):
                out[current][key] = line.split(":", 1)[1].split("#")[0].strip()
    for v in out.values():
        if v["scientific"]:
            v["scientific"] = " ".join(v["scientific"].split()[:2])
    return {sid: v for sid, v in out.items() if v["ebird"]}


# ---- Facts for the cards ----
def facts_of(entry):
    """The card's facts for one library entry: rounded measurements and the IUCN category."""
    traits = entry.get("traits") or {}
    out = {}
    if traits.get("massG"):
        m = traits["massG"]
        out["weight_g"] = round(m) if m >= 10 else round(m, 1)   # 26 g, but 8.5 g
    for key, name in (("wingMm", "wing_mm"), ("tailMm", "tail_mm")):
        if traits.get(key):
            out[name] = round(traits[key])
    iucn = (entry.get("conservation") or {}).get("iucn")
    if iucn:
        out["iucn"] = iucn
    return out


def write_facts(facts):
    """Write _data/bird_facts.yml: one short block per species, in species.yml's order."""
    lines = [
        "# Facts for the Avians bird cards. GENERATED by scripts/fetch_bird_facts.py; do not edit,",
        "# rerun the script. Measurements: AVONET (Tobias et al. 2022, CC BY 4.0), species means;",
        "# IUCN Red List category. Both from the huashu-bird-sticker library's data (MIT).",
        "",
    ]
    for sid, f in facts.items():
        lines.append(f"{sid}:")
        lines += [f"  {k}: {v}" for k, v in f.items()]
    FACTS_YML.write_text("\n".join(lines) + "\n")


# ---- Main ----
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", help="path to a local clone of huashu-bird-sticker (default: GitHub)")
    args = ap.parse_args()

    library = read_library(args.repo)
    # A few entries carry a list of eBird codes (e.g. after a split), most a single one.
    by_ebird, by_name = {}, {s["scientificName"]: s for s in library}
    for s in library:
        codes = (s.get("ids") or {}).get("ebird") or []
        for code in [codes] if isinstance(codes, str) else codes:
            by_ebird.setdefault(code, s)

    missing, facts = [], {}
    for sid, info in site_species().items():
        entry = by_name.get(info["scientific"]) or by_ebird.get(info["ebird"])
        if not entry:
            missing.append(f"{sid} ({info['ebird']})")
            continue
        facts[sid] = facts_of(entry)
        if info["iucn"]:
            facts[sid]["iucn"] = info["iucn"]          # set by hand in species.yml
        elif "iucn" not in facts[sid]:
            print(f"    note: {sid} has no IUCN category in the library; set `iucn:` in species.yml")

    write_facts(facts)
    print(f"wrote {FACTS_YML.relative_to(ROOT)} ({len(facts)} species)")
    if missing:
        print("Not in the library: " + ", ".join(missing), file=sys.stderr)


if __name__ == "__main__":
    main()
